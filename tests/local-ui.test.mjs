async function until(predicate) {
    for (let attempt = 0; attempt < 200; attempt++) {
        if (predicate()) return;
        await new Promise(resolve => setTimeout(resolve, 5));
    }
    assert.fail('UI tidak mencapai keadaan yang diharapkan. ' + [...(globalThis.document?.querySelectorAll('.form-error') || [])].map(node => node.textContent).filter(Boolean).join('; '));
}
async function app(t, { indexedDB = new IDBFactory(), url = 'http://localhost/' } = {}) {
    currency.setCurrency('IDR');
    const originals = new Map(['window', 'document', 'localStorage', 'indexedDB', 'FormData', 'Event', 'navigator'].map(key => [key, Object.getOwnPropertyDescriptor(globalThis, key)]));
    const dom = new JSDOM(readFileSync(new URL('../index.html', import.meta.url), 'utf8'), { url, runScripts: 'outside-only', pretendToBeVisual: true });
    const window = dom.window;
    window.matchMedia = () => ({ matches: false, addEventListener() {} });
    window.scrollTo = () => {};
    window.URL.createObjectURL = () => 'blob:http://localhost/test-photo';
    window.URL.revokeObjectURL = () => {};
    window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
    window.HTMLDialogElement.prototype.close = function () { this.open = false; window.setTimeout(() => this.dispatchEvent(new window.Event('close')), 0); };
    let serverCalls = 0;
    window.fetch = async () => { serverCalls++; throw new Error('Server tidak tersedia dalam pengujian.'); };
    for (const [key, value] of Object.entries({ window, document: window.document, localStorage: window.localStorage, indexedDB, FormData: window.FormData, Event: window.Event, navigator: window.navigator })) Object.defineProperty(globalThis, key, { configurable: true, writable: true, value });
    window.indexedDB = indexedDB;
    window.Blob = globalThis.Blob;
    window.eval(readFileSync(new URL('../assets/js/components/theme.js', import.meta.url), 'utf8'));
    const modules = new Map();
    function moduleAt(identifier) {
        if (!modules.has(identifier)) modules.set(identifier, new SourceTextModule(readFileSync(new URL(identifier), 'utf8'), { context: dom.getInternalVMContext(), identifier }));
        return modules.get(identifier);
    }
    const entry = moduleAt(new URL('../assets/js/app.js', import.meta.url).href);
    await entry.link((specifier, referencing) => moduleAt(new URL(specifier, referencing.identifier).href));
    await entry.evaluate();
    window.__closeSadaku = () => entry.namespace.runningApp.close();
    let cleaned = false;
    const close = async () => {
        if (cleaned) return;
        cleaned = true;
        try { await window.__closeSadaku(); } finally {
            window.close();
            for (const [key, descriptor] of originals) { if (descriptor) Object.defineProperty(globalThis, key, descriptor); else delete globalThis[key]; }
        }
    };
    t.after(close);
    await until(() => window.document.querySelector('#loading').hidden);
    return { window, $: selector => window.document.querySelector(selector), calls: () => serverCalls, close };
}

