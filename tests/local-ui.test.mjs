    assert.doesNotMatch($('.report-net').textContent, /Rp|EUR/);
    $('#report-album').value = rupiahId;
    $('#report-album').dispatchEvent(new window.Event('change', { bubbles: true }));
    assert.equal($('#report-currency').value, 'IDR');
