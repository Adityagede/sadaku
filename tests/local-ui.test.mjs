test('UI pemulihan memerlukan pratinjau dan persetujuan; berkas rusak tidak mengganti data', async t => {
    const { $, window } = await app(t);
    $('.settings-trigger').click();
    $('#app-menu [data-action="backup-settings"]').click();
    const values = new FormData();
    for (const [key, value] of Object.entries({ name: 'Dari cadangan', target: '90000', color: 'sage', motivation: '', plan_enabled: '0' })) values.set(key, value);
    const state = changeWallet(emptyWallet(), 'save_album', values).state;
    const file = new Blob([await encodeBackup(state)], { type: 'application/json' });
    function upload(value) {
        Object.defineProperty($('#restore-file'), 'files', { configurable: true, value: [value] });
        $('#restore-file').dispatchEvent(new window.Event('change', { bubbles: true }));
    }
    upload(file);
    await until(() => $('#restore-dialog').open);
    assert.match($('#restore-summary').textContent, /1 album, 0 catatan/);
    assert.equal($('#apply-restore').disabled, true);
    $('#restore-confirmation').click();
    assert.equal($('#apply-restore').disabled, false);
    $('#apply-restore').click();
    await until(() => !$('#restore-dialog').open);
    assert.match($('#album-grid').textContent, /Dari cadangan/);
    upload(new Blob(['{invalid'], { type: 'application/json' }));
    await until(() => $('#storage-settings').dataset.busy === 'false');
    assert.match($('#storage-settings .form-error').textContent, /JSON/);
    assert.equal($('#restore-dialog').open, false);
    assert.match($('#album-grid').textContent, /Dari cadangan/);
});

